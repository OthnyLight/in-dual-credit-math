#!/usr/bin/env python3
"""02_build.py — assemble the linked school-level files and the QA report.

Inputs : data/raw/{che,crdc,ccd,geo}  (from 01_fetch.py)
Outputs: data/processed/school_cohort_panel.csv   one row per public HS x graduating cohort
         data/processed/school_access.csv         one row per open public HS (map + access tables)
         data/processed/qa_report.txt

Run from repo root:  python code/02_build.py
"""
import io
import os
import re
import zipfile

import numpy as np
import pandas as pd
import zipfile_deflate64  # noqa: F401  (CCD 2021-22 inner zip uses Deflate64; this patches zipfile)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "data", "raw")
OUT = os.path.join(ROOT, "data", "processed")
os.makedirs(OUT, exist_ok=True)

COHORTS = [2019, 2021, 2022, 2023, 2024]          # 2020 cohort omitted (first college year = 2020-21, COVID)
CRDC_FOR_COHORT = {2019: "2021-22", 2021: "2021-22", 2022: "2021-22", 2023: "2023-24", 2024: "2023-24"}
CCD_FOR_CRDC = {"2021-22": "2122", "2023-24": "2324"}
QA = []


def qa(line=""):
    QA.append(line)
    print(line)


def num(s):
    """CHE cells: numbers, 'DS' (suppressed), blank. Anything non-numeric -> NaN."""
    return pd.to_numeric(s, errors="coerce")


def norm(name):
    return re.sub(r"[^a-z0-9]", "", str(name).lower())


# --------------------------------------------------------------------------- CHE
def load_che(y):
    d = pd.read_excel(os.path.join(RAW, "che", f"che_cohort{y}.xlsx"), sheet_name="Data", dtype=str)
    d = d.rename(columns={"HSGradsN": "HSGrads"})
    d = d[d.LocationType == "School"].copy()
    d["Location"] = d["Location"].str.strip()
    return d


che = {y: load_che(y) for y in COHORTS}

# name -> IDOE school number crosswalk, from the 2024 file (the only one with LocationId)
xw = (che[2024][["Location", "LocationId"]].drop_duplicates()
      .assign(key=lambda t: t.Location.map(norm)))
assert not xw.key.duplicated().any(), "2024 school names are not unique after normalising"
key2id = dict(zip(xw.key, xw.LocationId))

qa("=" * 78)
qa("QA REPORT — Dual-credit mathematics as a readiness lever (Indiana)")
qa("Generated by code/02_build.py")
qa("=" * 78)
qa("\n[1] CHE school rows and name linkage to IDOE school numbers")
rows = []
for y, d in che.items():
    if "LocationId" not in d:
        d["LocationId"] = d.Location.map(norm).map(key2id)
    n_sch = d.Location.nunique()
    unm = d[d.LocationId.isna()].Location.unique()
    qa(f"  cohort {y}: {n_sch} schools; linked to an IDOE number: {n_sch - len(unm)} "
       f"({(n_sch - len(unm)) / n_sch:.1%}); unlinked: {len(unm)}")
    pub_unm = [u for u in unm]  # listed in full below for the author to review
    if len(pub_unm):
        qa("    unlinked (closed/renamed schools; nonpublic schools are dropped later anyway): "
           + "; ".join(sorted(pub_unm)[:40]) + (" ..." if len(pub_unm) > 40 else ""))
    d = d[d.LocationId.notna()]

    def pick(cat, brk, col):
        s = d[(d.Category == cat) & (d.Breakout == brk)].set_index("LocationId")[col]
        return num(s)

    rec = pd.DataFrame({
        "grads": pick("Average", "Average", "HSGrads"),
        "enr_any": pick("Average", "Average", "EnrCollegeN"),
        "enr_inpub": pick("Average", "Average", "EnrINPubCollegeN"),
        "need_remed": pick("Average", "Average", "NeedRemedN"),
        "gpa": pick("Average", "Average", "AvgFreshmanGPA"),
        "credits": pick("Average", "Average", "AvgFreshmanCreditEarned"),
        "dc_n": pick("Dual Credit", "Earned Dual Credit from an Indiana Public College", "HSGrads"),
        "nodc_n": pick("Dual Credit", "Did Not Earn Dual Credit from an Indiana Public College", "HSGrads"),
        "dc_inpub": pick("Dual Credit", "Earned Dual Credit from an Indiana Public College", "EnrINPubCollegeN"),
        "nodc_inpub": pick("Dual Credit", "Did Not Earn Dual Credit from an Indiana Public College", "EnrINPubCollegeN"),
        "dc_gpa": pick("Dual Credit", "Earned Dual Credit from an Indiana Public College", "AvgFreshmanGPA"),
        "nodc_gpa": pick("Dual Credit", "Did Not Earn Dual Credit from an Indiana Public College", "AvgFreshmanGPA"),
        "dc_credits": pick("Dual Credit", "Earned Dual Credit from an Indiana Public College", "AvgFreshmanCreditEarned"),
        "nodc_credits": pick("Dual Credit", "Did Not Earn Dual Credit from an Indiana Public College", "AvgFreshmanCreditEarned"),
        "frl_n": pick("Socioeconomic Status", "Free or Reduced Lunch", "HSGrads"),
        "nonfrl_n": pick("Socioeconomic Status", "Non Free or Reduced Lunch", "HSGrads"),
        "ap_pass_n": pick("Advanced Placement", "Took and Passed an AP Test", "HSGrads"),
        "rem_math_only": pick("Remediation Type", "Math Only", "EnrINPubCollegeN"),
        "rem_both": pick("Remediation Type", "Both Math and English/Language Arts", "EnrINPubCollegeN"),
    })
    # name for display
    rec["che_name"] = d.drop_duplicates("LocationId").set_index("LocationId").Location
    rec["cohort"] = y
    rows.append(rec.reset_index().rename(columns={"LocationId": "idoe_sch"}))

panel = pd.concat(rows, ignore_index=True)

# recover a suppressed half of a two-way split from the total
for a, b, tot in [("dc_n", "nodc_n", "grads"), ("frl_n", "nonfrl_n", "grads")]:
    fill_a = panel[a].isna() & panel[b].notna() & panel[tot].notna()
    fill_b = panel[b].isna() & panel[a].notna() & panel[tot].notna()
    panel.loc[fill_a, a] = panel.loc[fill_a, tot] - panel.loc[fill_a, b]
    panel.loc[fill_b, b] = panel.loc[fill_b, tot] - panel.loc[fill_b, a]
    qa(f"  recovered suppressed '{a}' from total in {fill_a.sum()} school-cohorts, '{b}' in {fill_b.sum()}")

panel["dc_share"] = panel.dc_n / panel.grads
panel["frl_share"] = panel.frl_n / panel.grads
panel["ap_pass_share"] = panel.ap_pass_n.fillna(0).where(panel.grads.notna()) / panel.grads
panel["inpub_rate"] = panel.enr_inpub / panel.grads
panel["college_rate"] = panel.enr_any / panel.grads
panel["remed_rate"] = panel.need_remed / panel.enr_inpub
# math remediation: Math Only + Both. A '0' count is reported as 0 rows with blanks downstream;
# if the overall remediation count is 0, math remediation is 0.
mr = panel.rem_math_only.fillna(0) + panel.rem_both.fillna(0)
known = (panel.rem_math_only.notna() | panel.rem_both.notna() | (panel.need_remed == 0))
panel["math_remed_rate"] = (mr / panel.enr_inpub).where(known)
panel["dc_gpa_gap"] = panel.dc_gpa - panel.nodc_gpa
panel["dc_credit_gap"] = panel.dc_credits - panel.nodc_credits

# --------------------------------------------------------------------------- CCD
qa("\n[2] CCD directory, membership, and EDGE geocodes (Indiana)")
z = zipfile.ZipFile(os.path.join(RAW, "ccd", "ccd_sch_029_2324.zip"))
ccd = pd.read_csv(z.open("ccd_sch_029_2324_w_1a_073124.csv"), dtype=str, encoding="latin-1")
ccd = ccd[ccd.ST == "IN"].copy()
ccd["idoe_sch"] = ccd.ST_SCHID.str.split("-").str[-1]
ccd["idoe_corp"] = ccd.ST_LEAID.str.split("-").str[-1]
qa(f"  CCD 2023-24 Indiana schools: {len(ccd)}; IDOE school numbers unique: {not ccd.idoe_sch.duplicated().any()}")

z = zipfile.ZipFile(os.path.join(RAW, "ccd", "edge_geocode_2324.zip"))
edge_cols = ["NCESSCH", "LEAID", "NAME", "OPSTFIPS", "STREET", "CITY", "STATE", "ZIP", "STFIP", "CNTY", "NMCNTY",
             "LOCALE", "LAT", "LON", "CBSA", "NMCBSA", "CBSATYPE", "CSA", "NMCSA", "CD", "SLDL", "SLDU", "SCHOOLYEAR"]
edge = pd.read_csv(z.open("EDGE_GEOCODE_PUBLICSCH_2324/EDGE_GEOCODE_PUBLICSCH_2324.TXT"), sep="|", header=None,
                   names=edge_cols, dtype=str, encoding="latin-1")
assert edge.NCESSCH.str.fullmatch(r"\d{12}").mean() > 0.99, "EDGE layout changed: first column is not NCESSCH"
edge = edge[edge.STATE == "IN"][["NCESSCH", "CNTY", "NMCNTY", "LOCALE", "LAT", "LON"]]
edge["LAT"] = edge.LAT.astype(float)
edge["LON"] = edge.LON.astype(float)
LOC = {"1": "City", "2": "Suburb", "3": "Town", "4": "Rural"}
edge["locale4"] = edge.LOCALE.str[0].map(LOC)
qa(f"  EDGE geocodes for Indiana: {len(edge)}; locale coded: {edge.locale4.notna().mean():.1%}")


def membership(tag):
    z = zipfile.ZipFile(os.path.join(RAW, "ccd", f"ccd_sch_052_{tag}.zip"))
    names = z.namelist()
    csvs = [n for n in names if n.lower().endswith(".csv")]
    if csvs:
        fh = z.open(csvs[0])
    else:  # 2021-22 nests a zip inside the zip
        inner = zipfile.ZipFile(io.BytesIO(z.read([n for n in names if "CSV" in n][0])))
        fh = inner.open(inner.namelist()[0])
    keep = []
    for c in pd.read_csv(fh, dtype=str, encoding="latin-1", chunksize=500_000,
                         usecols=["ST", "NCESSCH", "LEAID", "GRADE", "TOTAL_INDICATOR", "STUDENT_COUNT"]):
        c = c[(c.ST == "IN") & (c.TOTAL_INDICATOR == "Subtotal 4 - By Grade") & c.GRADE.isin(["Grade 8", "Grade 9"])]
        keep.append(c)
    m = pd.concat(keep)
    m["n"] = pd.to_numeric(m.STUDENT_COUNT, errors="coerce")
    w = m.pivot_table(index=["NCESSCH", "LEAID"], columns="GRADE", values="n", aggfunc="sum").reset_index()
    return w.rename(columns={"Grade 8": "g8", "Grade 9": "g9"})


mem = {k: membership(v) for k, v in CCD_FOR_CRDC.items()}
for k, m in mem.items():
    qa(f"  CCD membership {k}: schools with grade 8: {m.g8.gt(0).sum()}, grade 9: {m.g9.gt(0).sum()}")

# --------------------------------------------------------------------------- CRDC
qa("\n[3] CRDC course and dual-enrollment files (Indiana)")


def crdc_year(tag):
    z = zipfile.ZipFile(os.path.join(RAW, "crdc", f"crdc_{tag}.zip"))

    def read(f, cols):
        d = pd.read_csv(z.open(f"SCH/{f}.csv"), dtype=str, encoding="latin-1")
        d = d[d.LEA_STATE == "IN"]
        out = d[["COMBOKEY", "LEAID"]].copy()
        for c in cols:
            if isinstance(c, tuple):
                name, parts = c
                vals = [pd.to_numeric(d[p], errors="coerce") for p in parts if p in d]
                v = pd.concat(vals, axis=1)
                v = v.where(v >= 0)                   # negatives are CRDC reserve codes -> missing
                out[name] = v.sum(axis=1, min_count=1)
            else:
                out[c] = d[c] if c in d else np.nan
        return out.set_index("COMBOKEY")

    tot = lambda stem: [f"TOT_{stem}_M", f"TOT_{stem}_F", f"TOT_{stem}_X"]
    de = read("Dual Enrollment", ["SCH_DUAL_IND", ("dual_n", tot("DUALENR"))])
    ca = read("Calculus", [("calc_classes", ["SCH_MATHCLASSES_CALC"]), ("calc_n", tot("MATHENR_CALC"))])
    am = read("Advanced Mathematics", [("advm_classes", ["SCH_MATHCLASSES_ADVM"]), ("advm_n", tot("MATHENR_ADVM"))])
    al = read("Algebra I", [("alg78_n", tot("ALGENR_G0708")), ("alg910_n", tot("ALGENR_GS0910")),
                            ("alg1112_n", tot("ALGENR_GS1112")), ("alg_hs_classes", ["SCH_MATHCLASSES_ALG"])])
    en = read("Enrollment", [("enr_total", tot("ENR"))])
    sc = read("School Characteristics", ["SCH_GRADE_G12", "SCH_VIRT_IND", "SCH_STATUS_ALT", "SCH_STATUS_CHARTER"])
    d = de.drop(columns="LEAID").join([ca.drop(columns="LEAID"), am.drop(columns="LEAID"),
                                        al.drop(columns="LEAID"), en.drop(columns="LEAID"), sc], how="outer")
    d["crdc_year"] = tag
    qa(f"  CRDC {tag}: Indiana schools {len(d)}; offering grade 12: {(d.SCH_GRADE_G12 == 'Yes').sum()}; "
       f"dual-enrollment indicator Yes: {(d.SCH_DUAL_IND == 'Yes').sum()}")
    return d


crdc = {t: crdc_year(t) for t in CCD_FOR_CRDC}

# corporation-level early Algebra I: grade 7-8 Algebra I enrollees / grade 8 membership, summed over the LEA
corp_alg = {}
for t, d in crdc.items():
    m = mem[t].set_index("NCESSCH")
    j = d[["LEAID", "alg78_n"]].join(m[["g8"]], how="left")
    g = j.groupby("LEAID").agg(alg78=("alg78_n", "sum"), g8=("g8", "sum"))
    g["corp_early_alg"] = (g.alg78 / g.g8).where(g.g8 >= 20)
    corp_alg[t] = g["corp_early_alg"]
    qa(f"  {t}: corporations with early-Algebra measure (>=20 eighth graders): {g.corp_early_alg.notna().sum()}; "
       f"median {g.corp_early_alg.median():.2f}; >1.0 (grade 7 takers inflate): {(g.corp_early_alg > 1).sum()}")


def school_crdc(t):
    d = crdc[t].copy()
    m = mem[t].set_index("NCESSCH")
    d = d.join(m[["g8", "g9"]], how="left")
    d["hs_alg_rate"] = ((d.alg910_n.fillna(0) + d.alg1112_n.fillna(0)) / d.g9).where(d.g9 >= 20)
    d["dual_any"] = (d.SCH_DUAL_IND == "Yes") & (d.dual_n.fillna(0) > 0)
    d["calc_offered"] = d.calc_classes.fillna(0) > 0
    d["advm_offered"] = d.advm_classes.fillna(0) > 0
    d["corp_early_alg"] = d.LEAID.map(corp_alg[t])
    hs_enr = d.enr_total
    d["dual_rate_crdc"] = d.dual_n / hs_enr
    d["calc_rate"] = d.calc_n / hs_enr
    return d


sch_crdc = {t: school_crdc(t) for t in crdc}

# --------------------------------------------------------------------------- link
qa("\n[4] Linking CHE school-cohorts to NCES / CRDC")
link = ccd[["NCESSCH", "idoe_sch", "idoe_corp", "LEAID", "SCH_NAME", "LEA_NAME", "SCH_TYPE_TEXT", "CHARTER_TEXT",
            "LEVEL", "G_12_OFFERED", "SY_STATUS_TEXT"]]
panel["public"] = panel.idoe_sch.str.fullmatch(r"\d+")
qa(f"  school-cohorts: {len(panel)}; with numeric (public) IDOE number: {panel.public.sum()}")
panel["idoe_sch"] = panel.idoe_sch.where(~panel.public, panel.idoe_sch.str.zfill(4))
panel = panel.merge(link, on="idoe_sch", how="left")
pub = panel[panel.public]
qa(f"  public school-cohorts matched to CCD 2023-24: {pub.NCESSCH.notna().sum()} of {len(pub)} "
   f"({pub.NCESSCH.notna().mean():.1%})")
qa("  public schools not in CCD 2023-24 (closed before 2023-24 or renumbered): "
   + "; ".join(sorted(pub[pub.NCESSCH.isna()].che_name.unique())))
panel = panel[panel.public & panel.NCESSCH.notna()].copy()
panel = panel[panel.idoe_corp != "9100"]            # Department of Correction facilities
qa(f"  after dropping nonpublic, unmatched, and correctional facilities: {len(panel)} school-cohorts, "
   f"{panel.NCESSCH.nunique()} schools")

parts = []
for t in crdc:
    p = panel[panel.cohort.map(CRDC_FOR_COHORT) == t].merge(
        sch_crdc[t].drop(columns=["LEAID"]), left_on="NCESSCH", right_index=True, how="left")
    parts.append(p)
panel = pd.concat(parts, ignore_index=True)
# fall back to the other CRDC year where the matched year is missing a measure
other = {"2021-22": "2023-24", "2023-24": "2021-22"}
for col in ["hs_alg_rate", "corp_early_alg", "calc_offered", "advm_offered", "dual_any", "dual_rate_crdc", "calc_rate"]:
    alt = panel.apply(lambda r: sch_crdc[other[r.crdc_year]][col].get(r.NCESSCH, np.nan)
                      if isinstance(r.crdc_year, str) else np.nan, axis=1)
    miss = panel[col].isna()
    panel.loc[miss, col] = alt[miss]
qa(f"  matched to CRDC: {panel.crdc_year.notna().mean():.1%}; "
   f"hs_alg_rate available: {panel.hs_alg_rate.notna().mean():.1%}; "
   f"corp_early_alg available: {panel.corp_early_alg.notna().mean():.1%}")
panel = panel.merge(edge, on="NCESSCH", how="left")
qa(f"  geocoded with locale: {panel.locale4.notna().mean():.1%}")
panel["virtual"] = panel.SCH_VIRT_IND.isin(["Yes", "Entirely virtual", "Primarily virtual"]) | \
    panel.SCH_NAME.str.contains("Virtual|Online|eAcademy|Digital", case=False, na=False)

# --------------------------------------------------------------------------- QA: ranges and sanity
qa("\n[5] Range and sanity checks (analytic panel)")
checks = {
    "dc_share in [0,1]": panel.dc_share.dropna().between(0, 1).all(),
    "frl_share in [0,1]": panel.frl_share.dropna().between(0, 1).all(),
    "gpa in [0,4]": panel.gpa.dropna().between(0, 4).all(),
    "credits in [0,60]": panel.credits.dropna().between(0, 60).all(),
    "remed_rate in [0,1]": panel.remed_rate.dropna().between(0, 1).all(),
    "dc_n + nodc_n == grads": ((panel.dc_n + panel.nodc_n - panel.grads).abs().dropna() < 0.5).all(),
    "enr_inpub <= grads": ((panel.enr_inpub - panel.grads).dropna() <= 0).all(),
    "no duplicate school-cohort": not panel.duplicated(["NCESSCH", "cohort"]).any(),
}
for k, v in checks.items():
    qa(f"  {'PASS' if v else 'FAIL'}  {k}")
assert all(checks.values()), "sanity check failed; see qa_report.txt"
for c in ["grads", "dc_share", "gpa", "credits", "remed_rate", "math_remed_rate", "frl_share", "ap_pass_share",
          "inpub_rate", "hs_alg_rate", "corp_early_alg", "dc_gpa_gap"]:
    s = panel[c]
    qa(f"  {c:16s} n={s.notna().sum():5d}  missing={s.isna().mean():6.1%}  "
       f"min={s.min():7.3f}  median={s.median():7.3f}  max={s.max():7.3f}")
qa("  hs_alg_rate > 1.2 (Algebra I repeaters or odd grade-9 counts): "
   f"{(panel.hs_alg_rate > 1.2).sum()} school-cohorts — capped at 1.2 in analysis")

qa("\n[6] Analytic-sample counts by cohort (public, linked, outcome GPA + exposure non-missing)")
ok = panel.gpa.notna() & panel.dc_share.notna()
qa(panel[ok].groupby("cohort").agg(schools=("NCESSCH", "nunique"), grads=("grads", "sum"),
                                   inpub=("enr_inpub", "sum")).to_string())

qa("\n[7] Named spot checks (verify against CHE dataset rows and CRDC school pages by hand)")
spots = ["Brownsburg High School", "Arsenal Technical High School", "Knox Community High School",
         "Bloomington High School South", "Gary"]
sp = panel[panel.cohort == 2024]
for s in spots:
    r = sp[sp.SCH_NAME.str.contains(s, case=False, na=False)].head(2)
    for _, x in r.iterrows():
        qa(f"  {x.SCH_NAME} ({x.NCESSCH}, IDOE {x.idoe_sch}) 2024: grads={x.grads:.0f} dc_share={x.dc_share:.3f} "
           f"inpub={x.enr_inpub} gpa={x.gpa} credits={x.credits} calc_offered={x.calc_offered} "
           f"dual_any={x.dual_any} locale={x.locale4}")
ext = panel[ok & (panel.cohort == 2024)]
for lab, r in [("highest dc_share", ext.nlargest(2, "dc_share")), ("lowest dc_share", ext.nsmallest(2, "dc_share"))]:
    for _, x in r.iterrows():
        qa(f"  {lab}: {x.SCH_NAME} 2024 dc_share={x.dc_share:.3f} grads={x.grads:.0f} gpa={x.gpa}")

panel.to_csv(os.path.join(OUT, "school_cohort_panel.csv"), index=False)

# --------------------------------------------------------------------------- access file (map)
qa("\n[8] Access file: open public high schools in 2023-24")
hs = ccd[(ccd.G_12_OFFERED == "Yes") & (ccd.SY_STATUS_TEXT.isin(["Open", "New", "Added", "Changed Boundary/Agency",
                                                                  "Reopened"])) &
         (ccd.idoe_corp != "9100")].copy()
qa(f"  CCD schools offering grade 12 (excluding correctional): {len(hs)}")
hs = hs.merge(edge, on="NCESSCH", how="left")
c24 = sch_crdc["2023-24"]
hs = hs.merge(c24[["dual_any", "dual_n", "dual_rate_crdc", "calc_offered", "advm_offered", "calc_n", "enr_total",
                   "hs_alg_rate", "corp_early_alg", "SCH_VIRT_IND", "SCH_STATUS_ALT"]],
              left_on="NCESSCH", right_index=True, how="left")
c22 = sch_crdc["2021-22"][["calc_offered", "advm_offered", "dual_any"]].add_suffix("_2122")
hs = hs.merge(c22, left_on="NCESSCH", right_index=True, how="left")
# offered in either CRDC year: small schools often run calculus in alternate years
hs["calc_either"] = hs.calc_offered.fillna(False).astype(bool) | hs.calc_offered_2122.fillna(False).astype(bool)
hs["dual_either"] = hs.dual_any.fillna(False).astype(bool) | hs.dual_any_2122.fillna(False).astype(bool)
qa(f"  calculus status changed between CRDC 2021-22 and 2023-24 at "
   f"{(hs.calc_offered.notna() & hs.calc_offered_2122.notna() & (hs.calc_offered != hs.calc_offered_2122)).sum()} "
   f"schools; access tiers use 'offered in either year'")
pooled =(panel[panel.cohort >= 2021].groupby("NCESSCH")
          .apply(lambda g: pd.Series({"dc_share_pooled": g.dc_n.sum(min_count=1) / g.grads[g.dc_n.notna()].sum(),
                                      "grads_pooled": g.grads.sum(),
                                      "frl_share_pooled": g.frl_n.sum(min_count=1) / g.grads[g.frl_n.notna()].sum()}),
                 include_groups=False))
hs = hs.merge(pooled, left_on="NCESSCH", right_index=True, how="left")
hs["virtual"] = hs.SCH_VIRT_IND.isin(["Yes", "Entirely virtual", "Primarily virtual"]) | \
    hs.SCH_NAME.str.contains("Virtual|Online|eAcademy|Digital", case=False, na=False)
hs["alt"] = hs.SCH_STATUS_ALT.eq("Yes") | hs.SCH_TYPE_TEXT.ne("Regular School")
qa(f"  matched to CRDC 2023-24: {hs.dual_any.notna().sum()} of {len(hs)}; with CHE grads (2021-24): "
   f"{hs.grads_pooled.notna().sum()}")
hs.to_csv(os.path.join(OUT, "school_access.csv"), index=False)

with open(os.path.join(OUT, "qa_report.txt"), "w", encoding="utf-8") as f:
    f.write("\n".join(QA) + "\n")
print("\nwrote school_cohort_panel.csv, school_access.csv, qa_report.txt")
